// Find StateInfo by id or alias
export function getStateInfo(stateId: string): StateInfo {
  const normalizedId = stateId.toLowerCase().trim();
  const targetId = STATE_ALIAS_MAP[normalizedId] || normalizedId;
  const found = STATES_LIST.find(s => s.id === targetId || s.id === normalizedId || s.code.toLowerCase() === normalizedId);
  return found || STATES_LIST[0]; // defaults to national if not found
}
