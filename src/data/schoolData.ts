// Helper function to search & query matching schools across all districts and zones
export function getMatchingGovtSchools(
  selectedDistrict: string,
  selectedZone: string,
  selectedCategory: string,
  query: string
): GovtSchoolItem[] {
  let list = MOCK_DELHI_GOVT_SCHOOLS;

  if (selectedDistrict !== 'All Districts') {
    list = list.filter(s => s.district.toLowerCase() === selectedDistrict.toLowerCase());
  }

  if (selectedZone !== 'All Zones') {
    list = list.filter(s => s.zone.toLowerCase() === selectedZone.toLowerCase());
  }

  if (selectedCategory !== 'All Categories') {
    list = list.filter(s => s.category.toLowerCase() === selectedCategory.toLowerCase());
  }

  const cleanQuery = query.trim().toLowerCase();
  if (!cleanQuery) return list;

  // Filter existing mock list
  const filtered = list.filter(s => 
    s.schoolId.includes(cleanQuery) ||
    s.name.toLowerCase().includes(cleanQuery) ||
    s.hindiName.includes(cleanQuery) ||
    s.area.toLowerCase().includes(cleanQuery) ||
    s.pincode.includes(cleanQuery) ||
    s.district.toLowerCase().includes(cleanQuery) ||
    s.zone.toLowerCase().includes(cleanQuery) ||
    s.streams.some(st => st.toLowerCase().includes(cleanQuery))
  );

  // Dynamic Generator for any 7-digit DoE School ID or query if user searches for an unlisted school code
  const isSchoolIdQuery = /^\d{7}$/.test(cleanQuery);
  if (filtered.length === 0 && (isSchoolIdQuery || cleanQuery.length >= 3)) {
    const code = isSchoolIdQuery ? cleanQuery : '1001' + Math.floor(100 + Math.random() * 800);
    const capitalizedQuery = cleanQuery.charAt(0).toUpperCase() + cleanQuery.slice(1);
    
    return [
      {
        id: `school-gen-${code}`,
        schoolId: code,
        name: isSchoolIdQuery ? `Delhi Govt School (DoE School ID: ${code})` : `Sarvodaya / Govt School - ${capitalizedQuery}`,
        hindiName: `दिल्ली सरकार विद्यालय (स्कूल आईडी: ${code})`,
        district: selectedDistrict !== 'All Districts' ? selectedDistrict : 'East Delhi',
        zone: selectedZone !== 'All Zones' ? selectedZone : 'Zone 01',
        category: 'Sarvodaya Vidyalaya (SKV/SBV)',
        gender: 'Co-Ed',
        shift: 'Morning',
        area: isSchoolIdQuery ? `Delhi Directorate of Education Zone` : `${capitalizedQuery}, Delhi`,
        pincode: '110001',
        streams: ['Science (PCB/PCM)', 'Commerce', 'Arts / Humanities', 'Vocational'],
        phone: '011-22521092 / 011-23890041 (DoE Helpline)',
        email: `school.${code}@edudel.nic.in`,
        principal: 'Head of School (HOS) / Vice Principal',
        address: `${capitalizedQuery} Govt School Campus, Directorate of Education, Govt. of NCT of Delhi`
      },
      ...filtered
    ];
  }

  return filtered;
}
