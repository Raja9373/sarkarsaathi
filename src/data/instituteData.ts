export function getMatchingGovtInstitutes(
  selectedCategory: string,
  selectedBody: string,
  query: string
): GovtInstituteItem[] {
  let list = MOCK_GOVT_INSTITUTES;

  if (selectedCategory !== 'All Categories') {
    list = list.filter(inst => inst.category.toLowerCase() === selectedCategory.toLowerCase());
  }

  if (selectedBody !== 'All Governing Bodies') {
    list = list.filter(inst => inst.governingBody.toLowerCase() === selectedBody.toLowerCase());
  }

  const cleanQuery = query.trim().toLowerCase();
  if (!cleanQuery) return list;

  return list.filter(inst => 
    inst.name.toLowerCase().includes(cleanQuery) ||
    inst.hindiName.includes(cleanQuery) ||
    inst.area.toLowerCase().includes(cleanQuery) ||
    inst.district.toLowerCase().includes(cleanQuery) ||
    inst.pincode.includes(cleanQuery) ||
    inst.igodRefCode.toLowerCase().includes(cleanQuery) ||
    inst.coursesOffered.some(c => c.toLowerCase().includes(cleanQuery))
  );
}
